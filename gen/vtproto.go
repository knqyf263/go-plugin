package gen

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/token"
	"path"
	"sort"
	"strconv"
	"strings"

	vtgenerator "github.com/planetscale/vtprotobuf/generator"
	"google.golang.org/protobuf/compiler/protogen"
)

const knownTypesImportPrefix = "github.com/knqyf263/go-plugin/types/known/"

func (gg *Generator) generateVTFile(f *fileInfo) {
	// It is a bit tricky, but necessary for workaround.
	// We create a dummyPlugin in memory.
	// Create the VTfile with it and then update its header
	dummyPlugin, err := protogen.Options{}.New(gg.plugin.Request)
	if err != nil {
		gg.plugin.Error(err)
		return
	}

	for _, file := range dummyPlugin.Files {
		replaceImports(file)

		if file.Desc.Path() == f.Desc.Path() &&
			file.Desc.Package() == "google.protobuf" {
			makeLocal(file)
		}
	}

	cfg := &vtgenerator.Config{}
	featureNames := []string{"marshal", "unmarshal", "size"}
	localVtGen, err := vtgenerator.NewGenerator(dummyPlugin, featureNames, cfg)
	if err != nil {
		gg.plugin.Error(err)
		return
	}

	localVtGen.Generate()

	targetFilename := f.GeneratedFilenamePrefix + "_vtproto.pb.go"
	var vtContent []byte
	for _, rf := range dummyPlugin.Response().File {
		if rf.GetName() == targetFilename {
			vtContent = []byte(rf.GetContent())
			break
		}
	}

	if len(vtContent) == 0 {
		return
	}

	vtContent = bytes.ReplaceAll(
		vtContent,
		[]byte("github.com/planetscale/vtprotobuf/types/known/"),
		[]byte(knownTypesImportPrefix),
	)

	vtContent, err = rewriteKnownTypes(vtContent, dummyPlugin, f.GoImportPath)
	if err != nil {
		gg.plugin.Error(err)
		return
	}

	vtContent, err = dedupeImports(vtContent)
	if err != nil {
		gg.plugin.Error(err)
		return
	}

	if idx := bytes.Index(vtContent, []byte("import ")); idx != -1 {
		vtContent = vtContent[idx:]
	}

	g := gg.plugin.NewGeneratedFile(targetFilename, f.GoImportPath)
	gg.generateHeader(g, f)
	g.Write(vtContent)
}

func makeLocal(file *protogen.File) {
	file.GoImportPath = ""

	var walk func([]*protogen.Message)
	walk = func(messages []*protogen.Message) {
		for _, message := range messages {
			message.GoIdent.GoImportPath = ""

			for _, enum := range message.Enums {
				enum.GoIdent.GoImportPath = ""
			}

			for _, oneof := range message.Oneofs {
				for _, field := range oneof.Fields {
					field.GoIdent.GoImportPath = ""
				}
			}

			walk(message.Messages)
		}
	}

	for _, enum := range file.Enums {
		enum.GoIdent.GoImportPath = ""
	}
	walk(file.Messages)
}

func rewriteKnownTypes(src []byte, plugin *protogen.Plugin, localImportPath protogen.GoImportPath) ([]byte, error) {
	known := collectKnownTypes(plugin)
	if len(known) == 0 {
		return src, nil
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}

	type replacement struct {
		offset int
		old    string
		new    string
	}

	replacements := make(map[token.Pos]replacement)
	imports := make(map[string]string)

	add := func(ident *ast.Ident) {
		goIdent, ok := known[ident.Name]
		if !ok ||
			goIdent.GoImportPath == "" ||
			goIdent.GoImportPath == localImportPath {
			return
		}

		importPath := string(goIdent.GoImportPath)
		importName := importNameForPath(file, importPath)
		if importName == "" {
			importName = path.Base(importPath)
			imports[importName] = importPath
		}

		replacements[ident.Pos()] = replacement{
			offset: fset.Position(ident.Pos()).Offset,
			old:    ident.Name,
			new:    importName + "." + ident.Name,
		}
	}

	var walkType func(ast.Expr)
	walkType = func(expr ast.Expr) {
		switch expr := expr.(type) {
		case nil:
			return

		case *ast.Ident:
			add(expr)

		case *ast.ArrayType:
			walkType(expr.Elt)

		case *ast.ChanType:
			walkType(expr.Value)

		case *ast.Ellipsis:
			walkType(expr.Elt)

		case *ast.FuncType:
			walkFields(expr.TypeParams, walkType)
			walkFields(expr.Params, walkType)
			walkFields(expr.Results, walkType)

		case *ast.IndexExpr:
			walkType(expr.X)
			walkType(expr.Index)

		case *ast.IndexListExpr:
			walkType(expr.X)
			for _, index := range expr.Indices {
				walkType(index)
			}

		case *ast.InterfaceType:
			walkFields(expr.Methods, walkType)

		case *ast.MapType:
			walkType(expr.Key)
			walkType(expr.Value)

		case *ast.ParenExpr:
			walkType(expr.X)

		case *ast.SelectorExpr:
			// Already qualified.

		case *ast.StarExpr:
			walkType(expr.X)

		case *ast.StructType:
			walkFields(expr.Fields, walkType)
		}
	}

	ast.Inspect(file, func(node ast.Node) bool {
		switch node := node.(type) {
		case *ast.Field:
			walkType(node.Type)

		case *ast.TypeSpec:
			walkType(node.Type)

		case *ast.ValueSpec:
			walkType(node.Type)

		case *ast.CompositeLit:
			walkType(node.Type)

		case *ast.TypeAssertExpr:
			walkType(node.Type)

		case *ast.CallExpr:
			// Type conversions generated by vtprotobuf, for example:
			//
			//     (*Any)(m.Value)
			//
			walkType(node.Fun)

			// Allocations such as new(Any).
			if ident, ok := node.Fun.(*ast.Ident); ok &&
				(ident.Name == "new" || ident.Name == "make") &&
				len(node.Args) != 0 {
				walkType(node.Args[0])
			}
		}

		return true
	})

	ordered := make([]replacement, 0, len(replacements))
	for _, replacement := range replacements {
		ordered = append(ordered, replacement)
	}

	// Work backwards so earlier offsets remain valid.
	sort.Slice(ordered, func(i, j int) bool {
		return ordered[i].offset > ordered[j].offset
	})

	for _, replacement := range ordered {
		src = append(
			src[:replacement.offset],
			append(
				[]byte(replacement.new),
				src[replacement.offset+len(replacement.old):]...,
			)...,
		)
	}

	for name, importPath := range imports {
		src = addImport(src, name, importPath)
	}

	return src, nil
}

func walkFields(fields *ast.FieldList, walk func(ast.Expr)) {
	if fields == nil {
		return
	}

	for _, field := range fields.List {
		walk(field.Type)
	}
}

func collectKnownTypes(plugin *protogen.Plugin) map[string]protogen.GoIdent {
	known := make(map[string]protogen.GoIdent)

	for _, file := range plugin.Files {
		walkMessages(file.Messages, func(message *protogen.Message) {
			addKnownType(known, message.GoIdent)

			for _, enum := range message.Enums {
				addKnownType(known, enum.GoIdent)
			}

			for _, oneof := range message.Oneofs {
				for _, field := range oneof.Fields {
					addKnownType(known, field.GoIdent)
				}
			}
		})

		for _, enum := range file.Enums {
			addKnownType(known, enum.GoIdent)
		}
	}

	return known
}

func addKnownType(known map[string]protogen.GoIdent, ident protogen.GoIdent) {
	if !strings.HasPrefix(string(ident.GoImportPath), knownTypesImportPrefix) {
		return
	}

	known[ident.GoName] = ident
}

func importNameForPath(file *ast.File, importPath string) string {
	for _, spec := range file.Imports {
		p, err := strconv.Unquote(spec.Path.Value)
		if err != nil || p != importPath {
			continue
		}

		if spec.Name != nil {
			if spec.Name.Name == "_" || spec.Name.Name == "." {
				return ""
			}
			return spec.Name.Name
		}

		return path.Base(importPath)
	}

	return ""
}

func addImport(src []byte, name, importPath string) []byte {
	needle := []byte("import (\n")
	index := bytes.Index(src, needle)
	if index == -1 {
		return src
	}

	index += len(needle)

	line := []byte("\t" + name + " " + strconv.Quote(importPath) + "\n")

	return append(src[:index], append(line, src[index:]...)...)
}
